"""API + approval workflow + PO tests (Phases 2, 4, 5). Uses a throwaway SQLite DB, never Neon."""
import csv
import io
import zipfile

import pytest
from fastapi.testclient import TestClient
from openpyxl import load_workbook
from pypdf import PdfReader

from planner_api import db
from planner_api.main import app
from planner_api.settings import get_settings
from reorder.io import read_dir

RAGHAV = {"X-Role": "raghav"}
PROC = {"X-Role": "procurement"}


@pytest.fixture()
def client(tmp_path, monkeypatch):
    db.init_engine(f"sqlite:///{tmp_path / 'test.db'}")
    monkeypatch.setattr(get_settings(), "gemini_api_key", "")  # template explanations, no network
    return TestClient(app)


def upload(client, oct_dir, run_date="2026-10-19", headers=RAGHAV, drop=None):
    files = [("files", (n, b, "text/csv")) for n, b in read_dir(oct_dir).items() if n != drop]
    return client.post("/api/runs", files=files, data={"run_date": run_date}, headers=headers)


def test_procurement_cannot_run(client, oct_dir):
    assert upload(client, oct_dir, headers=PROC).status_code == 403
    assert client.get("/api/runs").status_code == 401


def test_fatal_returns_exact_messages(client, oct_dir):
    r = upload(client, oct_dir, run_date="2026-10-30")
    assert r.status_code == 422
    assert "I7: inventory snapshot is stale or future-dated: 2026-10-19" in r.json()["validation"]["errors"]
    r = upload(client, oct_dir, drop="calendar.csv")
    assert "I1: missing file or column: calendar.csv" in r.json()["validation"]["errors"]


def full_flow(client, oct_dir):
    r = upload(client, oct_dir)
    assert r.status_code == 200, r.text
    run_id = r.json()["run_id"]
    s = r.json()["summary"]
    assert (s["reorder_now"], s["pause_next_order"], s["healthy"], s["total_units_now"], s["needs_review"]) == \
        (5, 2, 8, 1820, 4)
    ex = client.post(f"/api/runs/{run_id}/explain", headers=RAGHAV).json()
    assert len(ex["explanations"]) == 15
    assert all(e["source"] == "template" for e in ex["explanations"].values())
    assert ex["procurement_note"]

    # finalise blocked until every SKU has a decision
    assert client.post(f"/api/runs/{run_id}/finalise", headers=RAGHAV).status_code == 409
    # CHANGE/REJECT require notes
    bad = client.post(f"/api/runs/{run_id}/decisions", headers=RAGHAV,
                      json={"decisions": [{"sku_id": "SKU003", "decision": "CHANGE", "final_qty": 309}]})
    assert bad.status_code == 422
    assert client.post(f"/api/runs/{run_id}/decisions", headers=PROC,
                       json={"approve_all_unflagged": True}).status_code == 403
    r = client.post(f"/api/runs/{run_id}/decisions", headers=RAGHAV, json={"decisions": [
        {"sku_id": "SKU001", "decision": "APPROVE"},
        {"sku_id": "SKU003", "decision": "CHANGE", "final_qty": 309, "note": "Cover the 9-unit shortfall"},
        {"sku_id": "SKU007", "decision": "REJECT", "note": "Coconut water promo ending"},
        {"sku_id": "SKU013", "decision": "APPROVE"},
    ], "approve_all_unflagged": True})
    assert r.status_code == 200, r.text
    assert r.json()["decided"] == 15
    assert abs(r.json()["override_rate"] - 2 / 15) < 1e-9
    f = client.post(f"/api/runs/{run_id}/finalise", headers=RAGHAV)
    assert f.status_code == 200, f.text
    return run_id, f.json()["pos"]


def test_full_flow_and_pos(client, oct_dir):
    run_id, pos = full_flow(client, oct_dir)
    by_sup = {p["distributor_id"]: p for p in pos}
    assert sorted(by_sup) == ["DIST001", "DIST002", "DIST004"]
    assert {l["sku_id"]: l["quantity"] for l in by_sup["DIST001"]["lines"]} == {"SKU001": 750, "SKU013": 120}
    assert {l["sku_id"]: l["quantity"] for l in by_sup["DIST002"]["lines"]} == {"SKU003": 309, "SKU004": 150}
    assert {l["sku_id"]: l["quantity"] for l in by_sup["DIST004"]["lines"]} == {"SKU011": 500}
    for p in pos:
        assert p["total_qty"] == sum(l["quantity"] for l in p["lines"])
        assert p["po_number"].startswith("FR-PO-") and p["po_number"].endswith(f"-{p['distributor_id']}-001")
    all_skus = {l["sku_id"] for p in pos for l in p["lines"]}
    assert not all_skus & {"SKU006", "SKU007"}  # paused + rejected never appear
    assert {l["decision_source"] for p in pos for l in p["lines"]} == {"APPROVE", "CHANGE"}

    # locked
    assert client.post(f"/api/runs/{run_id}/decisions", headers=RAGHAV,
                       json={"decisions": [{"sku_id": "SKU001", "decision": "APPROVE"}]}).status_code == 409

    # every file opens
    pdf = client.get(f"/api/runs/{run_id}/pos/download?format=pdf", headers=PROC)
    reader = PdfReader(io.BytesIO(pdf.content))
    assert len(reader.pages) == 3
    text = "".join(pg.extract_text() for pg in reader.pages)
    assert "Approved by" in text and "Raghav Kulkarni" in text and "309" in text
    assert "Generated by Freshroots Reorder Planner. Enter in Zoho Inventory." in text
    wb = load_workbook(io.BytesIO(client.get(f"/api/runs/{run_id}/pos/download?format=xlsx", headers=PROC).content))
    assert wb.sheetnames[0] == "Summary" and wb.sheetnames[-1] == "Approval Log" and len(wb.sheetnames) == 5
    rows = list(csv.DictReader(io.StringIO(
        client.get(f"/api/runs/{run_id}/pos/download?format=csv", headers=PROC).text)))
    assert sum(int(r["Quantity"]) for r in rows) == 750 + 120 + 309 + 150 + 500
    z = zipfile.ZipFile(io.BytesIO(client.get(f"/api/runs/{run_id}/pos/download?format=zip", headers=PROC).content))
    assert z.testzip() is None
    assert "all_pos.pdf" in z.namelist() and "plan/reorder_plan_2026-10.csv" in z.namelist()
    one = client.get(f"/api/pos/{pos[0]['id']}/download?format=pdf", headers=PROC)
    assert len(PdfReader(io.BytesIO(one.content)).pages) == 1

    # statuses: Generated -> Downloaded -> Entered in Zoho (procurement only)
    listed = client.get(f"/api/runs/{run_id}/pos", headers=PROC).json()
    assert {p["status"] for p in listed} == {"Downloaded"}
    assert client.patch(f"/api/pos/{pos[0]['id']}", headers=RAGHAV,
                        json={"status": "Entered in Zoho", "zoho_ref": "PO-1"}).status_code == 403
    p = client.patch(f"/api/pos/{pos[0]['id']}", headers=PROC, json={"status": "Entered in Zoho", "zoho_ref": "PO-1"})
    assert p.json()["status"] == "Entered in Zoho"

    audit = client.get(f"/api/audit?run_id={run_id}", headers=PROC).json()
    actions = {a["action"] for a in audit}
    assert {"run.create", "decision.save", "run.finalise", "po.download", "po.entered_in_zoho"} <= actions
    change = next(a for a in audit if a["entity"] == "sku:SKU003")
    assert change["after"]["final_qty"] == 309 and change["after"]["engine_qty"] == 300


def test_plan_files_match_engine(client, oct_dir):
    run_id = upload(client, oct_dir).json()["run_id"]
