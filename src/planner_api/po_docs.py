"""PO documents (RULEBOOK v1.1 amendment 2): PDF, Excel, Zoho-import CSV and ZIP.

No prices exist in the input data, so price columns print as an em dash with a note.
"""
from __future__ import annotations

import csv
import io
import zipfile
from dataclasses import dataclass

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

DASH = "—"
NO_PRICE_NOTE = "Prices are not in the source data. Enter rates in Zoho Inventory."
FOOTER = "Generated by Freshroots Reorder Planner. Enter in Zoho Inventory."
APPROVER = "Raghav Kulkarni"


@dataclass
class PODoc:
    po_number: str
    po_date: str
    run_id: int
    order_month: str
    supplier_id: str
    supplier_name: str
    supplier_region: str
    approved_at: str          # display string in APP_TIMEZONE
    lines: list[dict]         # sku_id, sku_name, uom, quantity, decision_source
    company_name: str
    company_address: str

    @property
    def total(self) -> int:
        return sum(l["quantity"] for l in self.lines)


# ---------- PDF ----------

def _pdf_story(po: PODoc, styles) -> list:
    h = ParagraphStyle("h", parent=styles["Title"], fontName="Helvetica-Bold", fontSize=18, alignment=0,
                       spaceAfter=2)
    small = ParagraphStyle("s", parent=styles["Normal"], fontName="Helvetica", fontSize=9, leading=12,
                           textColor=colors.HexColor("#1d1d1f"))
    muted = ParagraphStyle("m", parent=small, textColor=colors.HexColor("#6e6e73"))
    story = [
        Paragraph(po.company_name, h),
        Paragraph(po.company_address or "", muted),
        Spacer(1, 6 * mm),
        Paragraph(f"<b>Purchase Order {po.po_number}</b>", ParagraphStyle("t", parent=small, fontSize=13, leading=16)),
        Spacer(1, 3 * mm),
    ]
    meta = [
        ["Supplier", f"{po.supplier_name} ({po.supplier_id})", "PO date", po.po_date],
        ["Region", po.supplier_region, "Order month", po.order_month],
        ["Approved by", f"{APPROVER}, {po.approved_at}", "Run ID", str(po.run_id)],
    ]
    mt = Table(meta, colWidths=[24 * mm, 70 * mm, 24 * mm, 52 * mm])
    mt.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, -1), "Helvetica", 9),
        ("FONT", (0, 0), (0, -1), "Helvetica-Bold", 9),
        ("FONT", (2, 0), (2, -1), "Helvetica-Bold", 9),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    story += [mt, Spacer(1, 6 * mm)]
    data = [["SKU ID", "SKU name", "UoM", "Quantity", "Unit price", "Amount", "Decision"]]
    for l in po.lines:
        data.append([l["sku_id"], Paragraph(l["sku_name"], small), l["uom"], f"{l['quantity']:,}", DASH, DASH,
                     l["decision_source"]])
    data.append(["", "Total", "", f"{po.total:,}", DASH, DASH, ""])
    t = Table(data, colWidths=[18 * mm, 62 * mm, 14 * mm, 20 * mm, 18 * mm, 18 * mm, 20 * mm], repeatRows=1)
    t.setStyle(TableStyle([
        ("FONT", (0, 0), (-1, 0), "Helvetica-Bold", 9),
        ("FONT", (0, 1), (-1, -1), "Helvetica", 9),
        ("FONT", (0, -1), (-1, -1), "Helvetica-Bold", 9),
        ("LINEBELOW", (0, 0), (-1, 0), 0.6, colors.HexColor("#1d1d1f")),
        ("LINEABOVE", (0, -1), (-1, -1), 0.6, colors.HexColor("#1d1d1f")),
        ("ALIGN", (3, 0), (5, -1), "RIGHT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -2), [colors.white, colors.HexColor("#f5f5f7")]),
    ]))
    story += [t, Spacer(1, 4 * mm), Paragraph(f"Note: {NO_PRICE_NOTE}", muted), Spacer(1, 8 * mm),
              Paragraph(FOOTER, muted)]
    return story


def po_pdf(pos: list[PODoc]) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=18 * mm,
                            bottomMargin=18 * mm, title="Freshroots purchase orders", author="Freshroots Reorder Planner")
    styles = getSampleStyleSheet()
    story: list = []
    for i, po in enumerate(pos):
        if i:
            story.append(PageBreak())
        story += _pdf_story(po, styles)
    doc.build(story)
    return buf.getvalue()


# ---------- Excel ----------

ARIAL = Font(name="Arial", size=10)
ARIAL_B = Font(name="Arial", size=10, bold=True)
HEAD_FILL = PatternFill("solid", fgColor="F5F5F7")


def _style(ws, header_row: int) -> None:
    for row in ws.iter_rows():
        for c in row:
            c.font = ARIAL
    for c in ws[header_row]:
        c.font = ARIAL_B
        c.fill = HEAD_FILL
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)


def _sheet_name(name: str, used: set[str]) -> str:
    base = "".join(ch for ch in name if ch not in "[]:*?/\\")[:31] or "Supplier"
    n, out = 2, base
    while out in used:
        suffix = f" {n}"
        out = base[: 31 - len(suffix)] + suffix
        n += 1
    used.add(out)
    return out


def po_xlsx(pos: list[PODoc], approval_log: list[dict]) -> bytes:
    wb = Workbook()
    sm = wb.active
    sm.title = "Summary"
    sm.append(["PO number", "Supplier", "Region", "PO date", "Order month", "Run ID", "Lines", "Total qty",
               "Approved by", "Approved at"])
    for po in pos:
        sm.append([po.po_number, po.supplier_name, po.supplier_region, po.po_date, po.order_month, po.run_id,
                   len(po.lines), po.total, APPROVER, po.approved_at])
    sm.append([])
    sm.append([NO_PRICE_NOTE])
    sm.append([FOOTER])
    _style(sm, 1)
    for col, w in zip("ABCDEFGHIJ", (26, 28, 14, 12, 12, 8, 8, 10, 18, 22)):
        sm.column_dimensions[col].width = w

    used = {"Summary", "Approval Log"}
    for po in pos:
        ws = wb.create_sheet(_sheet_name(po.supplier_name, used))
        ws.append([f"{po.company_name}: Purchase Order {po.po_number}"])
        ws.append([f"Supplier: {po.supplier_name} ({po.supplier_id}), {po.supplier_region}"])
        ws.append([f"PO date {po.po_date} | Run {po.run_id} | Order month {po.order_month} | "
                   f"Approved by {APPROVER} at {po.approved_at}"])
        ws.append([])
        ws.append(["SKU ID", "SKU name", "UoM", "Quantity", "Unit price", "Amount", "Decision"])
        for l in po.lines:
            ws.append([l["sku_id"], l["sku_name"], l["uom"], l["quantity"], DASH, DASH, l["decision_source"]])
        ws.append(["", "Total", "", po.total, DASH, DASH, ""])
        ws.append([])
        ws.append([NO_PRICE_NOTE])
        ws.append([FOOTER])
        _style(ws, 5)
        ws["A1"].font = Font(name="Arial", size=12, bold=True)
        ws.cell(row=6 + len(po.lines), column=2).font = ARIAL_B
        ws.cell(row=6 + len(po.lines), column=4).font = ARIAL_B
        for col, w in zip("ABCDEFG", (10, 40, 8, 10, 11, 10, 10)):
            ws.column_dimensions[col].width = w

    al = wb.create_sheet("Approval Log")
    al.append(["SKU ID", "Engine status", "Engine qty", "Decision", "Final qty", "Note", "Decided by", "Decided at"])
    for d in approval_log:
        al.append([d["sku_id"], d["status"], d["engine_qty"], d["decision"], d["final_qty"], d.get("note") or "",
                   d["decided_by"], d["decided_at"]])
    _style(al, 1)
    for col, w in zip("ABCDEFGH", (10, 18, 10, 10, 10, 48, 18, 22)):
        al.column_dimensions[col].width = w
    for row in al.iter_rows(min_row=2):
        row[5].alignment = Alignment(wrap_text=True)

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# ---------- CSV (Zoho Inventory import) ----------

# Generic purchase-order import layout. Column names follow Zoho Inventory's PO import
# field labels as best known; they were NOT verified against Zoho's live docs (no network
# access beyond Gemini). Map columns in Zoho's import wizard if any label differs.
ZOHO_COLUMNS = [
    "Purchase Order Number", "Purchase Order Date", "Vendor Name", "Reference#", "Item Name", "SKU",
    "Quantity", "Usage unit", "Rate", "Notes",
]


def po_csv(pos: list[PODoc]) -> bytes:
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(ZOHO_COLUMNS)
    for po in pos:
        for l in po.lines:
            w.writerow([po.po_number, po.po_date, po.supplier_name, f"Run {po.run_id} / {po.order_month}",
                        l["sku_name"], l["sku_id"], l["quantity"], l["uom"], "",
                        f"Approved by {APPROVER} ({l['decision_source']}). {NO_PRICE_NOTE}"])
    return buf.getvalue().encode("utf-8")


def po_zip(pos: list[PODoc], approval_log: list[dict], extras: dict[str, bytes] | None = None) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for po in pos:
            z.writestr(f"pdf/{po.po_number}.pdf", po_pdf([po]))
            z.writestr(f"csv/{po.po_number}.csv", po_csv([po]))
        z.writestr("all_pos.pdf", po_pdf(pos))
        z.writestr("all_pos.xlsx", po_xlsx(pos, approval_log))
        z.writestr("zoho_import_all_pos.csv", po_csv(pos))
        for name, data in (extras or {}).items():
            z.writestr(name, data)
    return buf.getvalue()
